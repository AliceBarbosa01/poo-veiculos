public class Veiculo {

    private int massa;
    private String cor;

    public void setMassa(int massa) {
        this.massa = massa;
    }

    public int getMassa() {
        return massa;
    }

    public void setCor(String cor) {
        this.cor = cor;
    }

    public String getCor() {
        return cor;
    }
}
